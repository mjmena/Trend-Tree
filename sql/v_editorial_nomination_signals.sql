-- Receipt URLs record what was supplied, even before signal ingestion or promotion.
-- The view owner needs receipt access; readers receive only this projection.
CREATE OR REPLACE SECURE VIEW MCC_PRESENTATION.TREND_AGENT.V_EDITORIAL_NOMINATION_SIGNALS
  COPY GRANTS
AS
SELECT DISTINCT
  n.NOMINATION_ID,
  u.value:canonical::VARCHAR AS SIGNAL_ID,
  n.STATUS,
  STRIP_NULL_VALUE(n.RESULT:trend_id)::VARCHAR AS TREND_ID,
  n.CREATED_AT AS ACCEPTED_AT
FROM MCC_RAW.MARKETING_DEV.STG_EDITORIAL_NOMINATIONS n,
     LATERAL FLATTEN(INPUT => n.REQUEST:urls) u;

-- The schema's default owner cannot read across databases into the private receipt.
GRANT OWNERSHIP ON VIEW MCC_PRESENTATION.TREND_AGENT.V_EDITORIAL_NOMINATION_SIGNALS
  TO ROLE MARKETING_ENGINEER COPY CURRENT GRANTS;

GRANT SELECT ON VIEW MCC_PRESENTATION.TREND_AGENT.V_EDITORIAL_NOMINATION_SIGNALS
  TO ROLE TH_APIROLE;
