-- Enrichment runs before the supporting-link task can publish a new candidate's evidence.
CREATE OR REPLACE VIEW MCC_RAW.MARKETING_DEV.V_TREND_CANDIDATE_EVIDENCE COPY GRANTS AS
WITH proposed AS (
    SELECT c.CANDIDATE_ID, s.value::VARCHAR AS signal_id
    FROM MCC_RAW.MARKETING_DEV.STG_TREND_CANDIDATES c, LATERAL FLATTEN(INPUT=>c.SUPPORTING_SIGNAL_IDS) s
), stories AS (
    SELECT DISTINCT p.CANDIDATE_ID, COALESCE(a.CREDITED_SIGNAL_ID,p.signal_id) AS signal_id
    FROM proposed p LEFT JOIN MCC_PRESENTATION.TREND_AGENT.FCT_ARTICLE_SIGNAL_ALIASES a ON a.SIGNAL_ID=p.signal_id
    QUALIFY BOOLOR_AGG(a.SIGNAL_ID IS NOT NULL) OVER (PARTITION BY p.CANDIDATE_ID)
), sources AS (
    SELECT e.CANDIDATE_ID,e.signal_id,COALESCE(MIN_BY(f.SOURCE_NAME,f.EMBEDDED_AT),MIN_BY(s.SOURCE_NAME,s.INGESTED_AT)) AS source_name
    FROM stories e
    LEFT JOIN MCC_PRESENTATION.TREND_AGENT.FCT_SIGNALS f ON f.SIGNAL_ID=e.signal_id
    LEFT JOIN MCC_RAW.MARKETING_DEV.STG_EXTERNAL_SIGNALS s ON s.SIGNAL_ID=e.signal_id AND f.SIGNAL_ID IS NULL
    GROUP BY e.CANDIDATE_ID,e.signal_id
), ids AS (
    SELECT CANDIDATE_ID,ARRAY_AGG(signal_id) WITHIN GROUP (ORDER BY signal_id) AS signal_ids FROM sources GROUP BY CANDIDATE_ID
), breakdown AS (
    SELECT CANDIDATE_ID,OBJECT_AGG(source_name,n::VARIANT) AS counts
    FROM (SELECT CANDIDATE_ID,source_name,COUNT(*) AS n FROM sources WHERE source_name IS NOT NULL GROUP BY 1,2)
    GROUP BY CANDIDATE_ID
)
SELECT c.CANDIDATE_ID,c.DEDUP_OF_TREND_ID,COALESCE(i.signal_ids,c.SUPPORTING_SIGNAL_IDS) AS SUPPORTING_SIGNAL_IDS,
       IFF(i.CANDIDATE_ID IS NULL,c.SOURCE_BREAKDOWN,COALESCE(b.counts,OBJECT_CONSTRUCT())) AS SOURCE_BREAKDOWN
FROM MCC_RAW.MARKETING_DEV.STG_TREND_CANDIDATES c
LEFT JOIN ids i ON i.CANDIDATE_ID=c.CANDIDATE_ID LEFT JOIN breakdown b ON b.CANDIDATE_ID=c.CANDIDATE_ID;

CREATE OR REPLACE PROCEDURE MCC_RAW.MARKETING_DEV.CAPTURE_ARTICLE_CANDIDATE_BIRTHS()
COPY GRANTS
RETURNS NUMBER LANGUAGE SQL EXECUTE AS CALLER AS
$$
BEGIN
    INSERT INTO MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_CANDIDATE_VERSIONS
        (CANDIDATE_ID,VERSION_AT_UTC,RECORDED_AT_UTC,PHASE,CHAIN_ID,CANDIDATE)
    SELECT c.CANDIDATE_ID,CONVERT_TIMEZONE('America/New_York','UTC',c.CREATED_AT),
           CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,'created',c.CHAIN_ID,
           OBJECT_DELETE(OBJECT_CONSTRUCT_KEEP_NULL(c.*),'PROMOTED_AT','PROMOTED_TO','DEDUP_OF_TREND_ID','PROMOTION_DECIDED_BY','REJECTED_AT',
               'REJECTION_REASON','DEFERRED_UNTIL','DEFER_REASON','ET_CORROBORATION','ET_WAS_SECOND_SOURCE')
    FROM MCC_RAW.MARKETING_DEV.STG_TREND_CANDIDATES c
    WHERE CONVERT_TIMEZONE('America/New_York','UTC',c.CREATED_AT) >= DATEADD(day,-7,(
        SELECT ENABLED_AT_UTC FROM MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_CONTROL WHERE LOCK_ID=1))
      AND NOT EXISTS (SELECT 1 FROM MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_CANDIDATE_VERSIONS v
                      WHERE v.CANDIDATE_ID=c.CANDIDATE_ID AND v.PHASE='created')
    QUALIFY ROW_NUMBER() OVER(PARTITION BY c.CANDIDATE_ID ORDER BY c.CREATED_AT)=1;
    RETURN SQLROWCOUNT;
END;
$$;

CREATE OR REPLACE PROCEDURE MCC_RAW.MARKETING_DEV.ACQUIRE_ARTICLE_COMPARISON_POOL(
    LANE VARCHAR, CHAIN_ID VARCHAR, SESSION_ID VARCHAR, LOOKBACK_HOURS FLOAT, SOURCE_CAP FLOAT, POOL_LIMIT FLOAT, MIN_POOL FLOAT
)
COPY GRANTS
RETURNS ARRAY LANGUAGE JAVASCRIPT EXECUTE AS CALLER AS
$$
if (LANE!=='main' && LANE!=='revisit') throw new Error('Unknown distillation lane');
function execute(sqlText,binds) {
    return snowflake.createStatement({sqlText:sqlText,binds:binds || []}).execute();
}
const clock = execute(`SELECT UUID_STRING(),TO_VARCHAR(CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP()),'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"')`);
clock.next();
const id = clock.getColumnValue(1), observed = clock.getColumnValue(2);
const snapshot = " AT(TIMESTAMP=>'"+observed+"'::TIMESTAMP_TZ)";
execute('BEGIN TRANSACTION');
try {
    execute(`INSERT INTO MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_POOL_SIGNALS
        (OPPORTUNITY_ID,SIGNAL_ID,INPUT_ORDINAL,SOURCE_NAME,SIGNAL_TITLE,SIGNAL_TEXT,METADATA,INGESTED_AT_UTC,EMBEDDED_AT_UTC,
         CLAIM_SESSION_ID,SIGNAL_KIND,HAD_PROMOTED_CANDIDATE,CREDITED_SIGNAL_ID,POOL_RANK)
        WITH promoted AS (
            SELECT DISTINCT f.value::VARCHAR signal_id FROM MCC_RAW.MARKETING_DEV.STG_TREND_CANDIDATES ${snapshot} c,
            LATERAL FLATTEN(INPUT=>c.SUPPORTING_SIGNAL_IDS) f WHERE c.PROMOTED_TO IS NOT NULL
        ), embedded AS (
            SELECT SIGNAL_ID,MIN(EMBEDDED_AT) embedded_at FROM MCC_PRESENTATION.TREND_AGENT.FCT_SIGNALS ${snapshot}
            WHERE SIGNAL_VECTOR IS NOT NULL GROUP BY SIGNAL_ID
        ), aliases AS (
            SELECT SIGNAL_ID,CREDITED_SIGNAL_ID FROM MCC_PRESENTATION.TREND_AGENT.FCT_ARTICLE_SIGNAL_ALIASES ${snapshot}
            QUALIFY ROW_NUMBER() OVER(PARTITION BY SIGNAL_ID ORDER BY VERIFIED_AT_UTC DESC,CREDITED_SIGNAL_ID)=1
        ), credited_promotions AS (
            SELECT DISTINCT COALESCE(a.CREDITED_SIGNAL_ID,p.SIGNAL_ID) AS signal_id
            FROM promoted p LEFT JOIN aliases a ON a.SIGNAL_ID=p.SIGNAL_ID
        ), inputs AS (
            -- The workflow applies its slot caps before discarding empty IDs from the returned pool.
            SELECT COALESCE(s.SIGNAL_ID,'') AS SIGNAL_ID,s.SOURCE_NAME,s.SIGNAL_TITLE,s.SIGNAL_TEXT,s.METADATA,
                   CONVERT_TIMEZONE('America/New_York','UTC',s.INGESTED_AT) ingested,
                   CONVERT_TIMEZONE('America/New_York','UTC',f.EMBEDDED_AT) embedded,s.AGENT_SESSION_ID claim,
                   COALESCE(s.METADATA:signal_kind::VARCHAR,'discovery_signal') kind,
                   p.SIGNAL_ID IS NOT NULL had_promotion,cp.SIGNAL_ID IS NOT NULL credited_promotion,a.CREDITED_SIGNAL_ID alias_id
            FROM MCC_RAW.MARKETING_DEV.STG_EXTERNAL_SIGNALS ${snapshot} s
            LEFT JOIN embedded f ON f.SIGNAL_ID=s.SIGNAL_ID
            LEFT JOIN aliases a ON a.SIGNAL_ID=s.SIGNAL_ID
            LEFT JOIN promoted p ON p.SIGNAL_ID=s.SIGNAL_ID
            LEFT JOIN credited_promotions cp ON cp.SIGNAL_ID=COALESCE(a.CREDITED_SIGNAL_ID,s.SIGNAL_ID)
            WHERE s.INGESTED_AT > CONVERT_TIMEZONE('UTC','America/New_York',DATEADD(hour,-?,?::TIMESTAMP_NTZ))
        ), numbered AS (
            SELECT i.*,ROW_NUMBER() OVER(PARTITION BY SIGNAL_ID ORDER BY ingested DESC,SOURCE_NAME,claim,
                HASH(SIGNAL_TITLE,SIGNAL_TEXT,METADATA)) input_ordinal FROM inputs i
        ), tracked AS (
            SELECT DISTINCT SIGNAL_ID FROM MCC_RAW.MARKETING_DEV.STG_ARTICLE_EVIDENCE_KEYS ${snapshot} WHERE HAS_TREND_HUNTER
        ), representatives AS (
            SELECT i.SIGNAL_ID,i.input_ordinal,i.SOURCE_NAME,i.ingested FROM numbered i
            LEFT JOIN tracked t ON t.SIGNAL_ID=i.SIGNAL_ID
            WHERE i.alias_id IS NULL AND i.kind='discovery_signal'
              AND IFF(?='main',COALESCE(i.claim,'')='',i.claim LIKE 'sess-%' AND NOT i.credited_promotion)
            QUALIFY t.SIGNAL_ID IS NULL OR ROW_NUMBER() OVER(PARTITION BY i.SIGNAL_ID ORDER BY i.input_ordinal)=1
        ), eligible AS (
            SELECT SIGNAL_ID,input_ordinal,ingested FROM representatives
            QUALIFY ROW_NUMBER() OVER(PARTITION BY SOURCE_NAME ORDER BY ingested DESC,SIGNAL_ID,input_ordinal)<=?
        ), selected AS (
            SELECT SIGNAL_ID,input_ordinal,ROW_NUMBER() OVER(ORDER BY ingested DESC,SIGNAL_ID,input_ordinal) pool_rank FROM eligible QUALIFY pool_rank<=?
        )
        SELECT ?,i.SIGNAL_ID,i.input_ordinal,i.SOURCE_NAME,i.SIGNAL_TITLE,i.SIGNAL_TEXT,i.METADATA,i.ingested,i.embedded,i.claim,
               i.kind,i.had_promotion,COALESCE(i.alias_id,i.SIGNAL_ID),IFF(i.SIGNAL_ID='',NULL,p.pool_rank)
        FROM numbered i LEFT JOIN selected p ON p.SIGNAL_ID=i.SIGNAL_ID AND p.input_ordinal=i.input_ordinal`,[LOOKBACK_HOURS,observed,LANE,SOURCE_CAP,POOL_LIMIT,id]);
    const pool = execute(`SELECT ARRAY_AGG(SIGNAL_ID) WITHIN GROUP(ORDER BY POOL_RANK)
        FROM MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_POOL_SIGNALS WHERE OPPORTUNITY_ID=? AND POOL_RANK IS NOT NULL`,[id]);
    pool.next();
    const ids=pool.getColumnValue(1);
    execute(`INSERT INTO MCC_RAW.MARKETING_DEV.STG_TREND_HUNTER_OPPORTUNITIES
        (OPPORTUNITY_ID,OBSERVED_AT_UTC,LANE,CHAIN_ID,SESSION_ID,LOOKBACK_HOURS,PER_SOURCE_CAP,POOL_LIMIT,MIN_POOL,SELECTED_COUNT,PASSED_FLOOR)
        SELECT ?,?::TIMESTAMP_NTZ,?,?,?,?,?,?,?,?,? >= ?`,[id,observed,LANE,CHAIN_ID,SESSION_ID,LOOKBACK_HOURS,SOURCE_CAP,POOL_LIMIT,MIN_POOL,ids.length,ids.length,MIN_POOL]);
    execute('COMMIT');
    return ids;
} catch (error) {
    execute('ROLLBACK');
    throw error;
}
$$;
