-- Read-only editorial worksheet; no percentage is inferred from cosine.
-- Collection IDs/descriptions reflect CUE metadata at query time, not match time.
WITH latest_chain AS (
    SELECT CHAIN_ID, COMPUTED_AT
    FROM MCC_PRESENTATION.TREND_AGENT.FCT_TREND_CONTENT_MATCHES_LEDGER
    QUALIFY ROW_NUMBER() OVER (ORDER BY COMPUTED_AT DESC, CHAIN_ID DESC) = 1
),
content_metadata AS (
    SELECT CONTENTID, CLUSTER_ID, CLUSTER_DESCRIPTION
    FROM MCC_RAW.STORY_DATA.CUE_CONTENT_VECTORS
    WHERE CLUSTER_ID IS NOT NULL
      AND NULLIF(TRIM(CLUSTER_DESCRIPTION), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CONTENTID
        ORDER BY PUBLISHED_DATE DESC NULLS LAST, CLUSTER_ID, CLUSTER_DESCRIPTION
    ) = 1
),
collection_articles AS (
    SELECT m.TREND_ID, c.CLUSTER_ID, c.CLUSTER_DESCRIPTION,
           m.CONTENT_ID, m.HEADLINE, m.PUBLISHED_DATE, m.SCORE,
           m.MATCH_THRESHOLD, m.WINDOW_DAYS, m.COMPUTATION_VERSION,
           COUNT(*) OVER (PARTITION BY m.TREND_ID, c.CLUSTER_ID) AS RETRIEVED_ARTICLES
    FROM MCC_PRESENTATION.TREND_AGENT.FCT_TREND_CONTENT_MATCHES_LEDGER m
    JOIN latest_chain l ON l.CHAIN_ID = m.CHAIN_ID
    JOIN content_metadata c ON c.CONTENTID = m.CONTENT_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY m.TREND_ID, c.CLUSTER_ID
        ORDER BY m.SCORE DESC, m.CONTENT_ID, m.CONTENT_MATCH_ID
    ) = 1
),
top_collection AS (
    SELECT *
    FROM collection_articles
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TREND_ID
        ORDER BY SCORE DESC, CLUSTER_ID, CONTENT_ID
    ) = 1
)
SELECT d.TREND_ID, d.TREND_NAME, d.CATEGORY, d.SUMMARY_SHORT,
       l.CHAIN_ID, l.COMPUTED_AT,
       c.CLUSTER_ID AS PROPOSED_COLLECTION_ID,
       c.CLUSTER_DESCRIPTION AS PROPOSED_COLLECTION,
       c.SCORE AS TOP_COSINE, c.RETRIEVED_ARTICLES,
       c.CONTENT_ID, c.HEADLINE, c.PUBLISHED_DATE,
       c.MATCH_THRESHOLD, c.WINDOW_DAYS, c.COMPUTATION_VERSION,
       CURRENT_TIMESTAMP() AS METADATA_READ_AT,
       NULL::VARCHAR AS EDITORIAL_EXPECTED_COLLECTION,
       NULL::NUMBER(5,2) AS EDITORIAL_MATCH_PERCENT,
       NULL::VARCHAR AS EDITORIAL_NOTES
FROM MCC_PRESENTATION.TREND_AGENT.DT_TREND_DASHBOARD d
LEFT JOIN latest_chain l ON TRUE
LEFT JOIN top_collection c ON c.TREND_ID = d.TREND_ID
WHERE COALESCE(d.LIFECYCLE_STATUS, 'NEW') <> 'RETIRED'
ORDER BY TOP_COSINE DESC NULLS LAST, d.TREND_ID;
