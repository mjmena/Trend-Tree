);

CREATE OR REPLACE TEMPORARY TABLE MERGE_EXTERNAL_SIGNALS_CHECKS AS
SELECT 'duplicate existing ID gets one session update and preserves its first-seen title' AS CHECK_NAME,
       (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE WHERE SIGNAL_ID = 'existing') = 1
       AND (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE
            WHERE SIGNAL_ID = 'existing' AND AGENT_SESSION_ID = 'fixture-session'
              AND SIGNAL_TITLE = 'original title') = 1 AS PASS
UNION ALL
SELECT 'duplicate new ID inserts one row with the earliest signal timestamp',
       (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE WHERE SIGNAL_ID = 'new') = 1
       AND (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE
            WHERE SIGNAL_ID = 'new' AND SIGNAL_TITLE = 'earliest'
              AND SIGNAL_TIMESTAMP = '2026-11-19 11:00:00'::TIMESTAMP_NTZ) = 1
UNION ALL
SELECT 'an existing session is preserved',
       (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE
        WHERE SIGNAL_ID = 'claimed' AND AGENT_SESSION_ID = 'original-session'
          AND SIGNAL_TITLE = 'claimed title') = 1
UNION ALL
SELECT 'timestamp ties retain the first input row',
       (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE WHERE SIGNAL_ID = 'tied') = 1
       AND (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE
            WHERE SIGNAL_ID = 'tied' AND SIGNAL_TITLE = 'first') = 1
UNION ALL
SELECT 'the rest of the batch is inserted',
       (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE) = 5
       AND (SELECT COUNT(*) FROM MERGE_EXTERNAL_SIGNALS_FIXTURE
            WHERE SIGNAL_ID = 'unique' AND AGENT_SESSION_ID = 'fixture-session') = 1;

SELECT CHECK_NAME, PASS FROM MERGE_EXTERNAL_SIGNALS_CHECKS ORDER BY CHECK_NAME;

SELECT 1 / IFF(COUNT_IF(NOT PASS OR PASS IS NULL) = 0, 1, 0) AS ALL_CHECKS_PASSED
FROM MERGE_EXTERNAL_SIGNALS_CHECKS;
